// Run against a dedicated PostgreSQL database. The SQLite source is read-only.
import Database from "better-sqlite3";
import pg from "pg";
import { readFile } from "node:fs/promises";
import path from "node:path";

const tables = [
  "users",
  "sessions",
  "completed_labs",
  "attempts",
  "quiz_results",
  "hint_views",
  "evidence_notebooks",
  "reports",
  "classes",
  "class_enrollments",
  "schema_meta",
  "courses",
  "course_modules",
  "lab_catalog",
  "course_lessons",
  "learning_paths",
  "path_courses",
];
const ordered = new Set([
  "completed_labs",
  "attempts",
  "quiz_results",
  "hint_views",
  "evidence_notebooks",
  "reports",
]);
const args = process.argv.slice(2);
if (
  !process.env.DATABASE_URL ||
  args.some((a) => !["--init", "--verify"].includes(a)) ||
  args.length > 1
)
  throw new Error(
    "Set DATABASE_URL and run with no arguments to copy, --init for schema, or --verify for comparison.",
  );
const db = args.includes("--init")
  ? null
  : new Database(
      path.join(
        process.env.VULNMENTOR_DATA_DIR || ".data",
        "vulnmentor.sqlite",
      ),
      { readonly: true, fileMustExist: true },
    );
const client = new pg.Client({ connectionString: process.env.DATABASE_URL });
try {
  await client.connect();
  await client.query("BEGIN");
  await client.query("SELECT pg_advisory_xact_lock(6931881)");
  const schema = await readFile(
    new URL("../src/lib/store/schema.sql", import.meta.url),
    "utf8",
  );
  if (!args.includes("--verify")) {
    await client.query(schema);
    for (const table of ordered)
      await client.query(
        `ALTER TABLE ${table} ADD COLUMN IF NOT EXISTS rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE`,
      );
  }
  if (db) {
    db.exec("BEGIN");
    for (const table of tables) {
      if (
        !db
          .prepare("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?")
          .get(table)
      )
        continue;
      const fields = db.pragma("table_info(" + table + ")").map((f) => f.name);
      if (ordered.has(table)) fields.push("rowid");
      const list = fields.join(",");
      const rows = db
        .prepare("SELECT " + list + " FROM " + table + " ORDER BY rowid")
        .all();
      if (!args.includes("--verify")) {
        for (const row of rows)
          await client.query(
            `INSERT INTO ${table}(${list}) VALUES(${fields.map((_, i) => "$" + (i + 1))}) ON CONFLICT DO NOTHING`,
            fields.map((f) => row[f]),
          );
      }
      const target = await client.query("SELECT " + list + " FROM " + table);
      const key = (row) =>
        JSON.stringify(
          fields.map((f) => (f === "rowid" ? String(row[f]) : row[f])),
        );
      const found = new Set(target.rows.map(key));
      if (
        found.size !== rows.length ||
        rows.some((row) => !found.has(key(row)))
      )
        throw new Error(
          "Verification failed for " +
            table +
            "; transaction rolled back. Use an empty target.",
        );
      if (ordered.has(table) && rows.length && !args.includes("--verify")) {
        // Restart the identity transactionally. Migrated rows retain source order.
        const next = BigInt(rows.at(-1).rowid) + 1n;
        await client.query(
          `ALTER TABLE ${table} ALTER COLUMN rowid RESTART WITH ${next}`,
        );
      }
      console.log(table, rows.length, "verified");
    }
  }
  await client.query("COMMIT");
} catch (error) {
  await client.query("ROLLBACK").catch(() => {});
  throw error;
} finally {
  db?.close();
  await client.end();
}
